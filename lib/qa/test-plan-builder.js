function _detectDependencies(parsed) {
  const deps = [];
  if (parsed.hasBrowserUi) deps.push('Chrome MCP (L3-L5)');
  if (parsed.hasDatabase) deps.push('Database access (L5)');
  if (parsed.hasAuth) deps.push('Auth credentials (L2-L4)');
  return deps;
}

// br124: tag each fenced block with its language so L1 extraction can limit
// itself to js/ts blocks. Shape: { lang: string, code: string }.
function _extractCodeBlocks(content) {
  const blocks = [];
  const regex = /```([\w-]*)\n([\s\S]*?)```/g;
  let match;
  while ((match = regex.exec(content)) !== null) {
    blocks.push({ lang: (match[1] || '').toLowerCase(), code: match[2] });
  }
  return blocks;
}

